import streamlit as st
import pandas as pd
import numpy as np
import joblib
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.metrics import (accuracy_score, roc_auc_score, precision_score,
                             recall_score, f1_score, matthews_corrcoef,
                             confusion_matrix, classification_report)

st.set_page_config(page_title="Adult Income Classifier", layout="wide")

st.title("Adult Income Classification — Model Evaluator")
st.markdown(
    "Pre-trained classifiers that predict whether a person's income exceeds $50K/year. "
    "Upload the test CSV, choose a model, and view evaluation metrics. "
    "**No retraining occurs — models are loaded from saved pipelines.**"
)

# ── Constants ─────────────────────────────────────────────────────────────────
MODEL_FILES = {
    "Logistic Regression":    "model/logistic_regression.joblib",
    "Decision Tree":          "model/decision_tree.joblib",
    "K-Nearest Neighbor":     "model/knn.joblib",
    "Naive Bayes":            "model/naive_bayes.joblib",
    "Support Vector Machine": "model/svm.joblib",
}
MODEL_DESCRIPTIONS = {
    "Logistic Regression":    "Linear decision boundary. Fast, interpretable baseline. Scaling: StandardScaler (inside pipeline). max_iter=1000.",
    "Decision Tree":          "Splits data on feature thresholds. Captures non-linear patterns. max_depth=10, no scaling needed.",
    "K-Nearest Neighbor":     "Labels by majority vote of 7 nearest neighbours. Scaling: StandardScaler (inside pipeline). n_neighbors=7.",
    "Naive Bayes":            "Probabilistic model assuming feature independence. Gaussian variant. Works on scaled features.",
    "Support Vector Machine": "Finds optimal hyperplane with RBF kernel. Scaling: StandardScaler (inside pipeline). C=1.0.",
}
TARGET_COL = "income"

# ── Load model (cached) ───────────────────────────────────────────────────────
@st.cache_resource
def load_model(path):
    return joblib.load(path)

# ── Sidebar ───────────────────────────────────────────────────────────────────
st.sidebar.header("Controls")

with open("test_data.csv", "rb") as f:
    st.sidebar.download_button("Download sample test_data.csv", f,
                               file_name="test_data.csv", mime="text/csv")

uploaded_file = st.sidebar.file_uploader("Upload test_data.csv", type=["csv"])
model_choice  = st.sidebar.selectbox("Select Model", list(MODEL_FILES.keys()))
st.sidebar.markdown(f"*{MODEL_DESCRIPTIONS[model_choice]}*")

if uploaded_file is None:
    st.info("Upload `test_data.csv` using the sidebar to get started. "
            "Use the download button above to get the sample file.")
    st.stop()

# ── Load and validate data ────────────────────────────────────────────────────
df = pd.read_csv(uploaded_file)

if TARGET_COL not in df.columns:
    st.error(f"Target column `{TARGET_COL}` not found. Upload the test_data.csv generated by the training script.")
    st.stop()

X = df.drop(columns=[TARGET_COL])
y = df[TARGET_COL]

# ── Tabs ──────────────────────────────────────────────────────────────────────
tab1, tab2, tab3 = st.tabs(["Evaluation", "Model Comparison", "Data"])

# ══════════════════════════════════════════════════════════════════════════════
with tab1:
    st.subheader(f"Evaluation — {model_choice}")
    st.caption(f"Source: {uploaded_file.name}  |  Rows: {len(df)}  |  Features: {X.shape[1]}")

    model  = load_model(MODEL_FILES[model_choice])
    y_pred = model.predict(X)
    y_prob = model.predict_proba(X)[:, 1]

    metrics = {
        "Accuracy":  round(accuracy_score(y, y_pred),   4),
        "AUC":       round(roc_auc_score(y, y_prob),    4),
        "Precision": round(precision_score(y, y_pred),  4),
        "Recall":    round(recall_score(y, y_pred),     4),
        "F1 Score":  round(f1_score(y, y_pred),         4),
        "MCC":       round(matthews_corrcoef(y, y_pred), 4),
    }

    cols = st.columns(6)
    for col, (name, val) in zip(cols, metrics.items()):
        col.metric(name, val)

    st.markdown("---")
    col_cm, col_cr = st.columns([1, 1])

    with col_cm:
        st.subheader("Confusion Matrix")
        cm = confusion_matrix(y, y_pred)
        fig, ax = plt.subplots(figsize=(4, 3.5))
        sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', ax=ax,
                    xticklabels=['<=50K', '>50K'],
                    yticklabels=['<=50K', '>50K'])
        ax.set_xlabel("Predicted")
        ax.set_ylabel("Actual")
        st.pyplot(fig)

    with col_cr:
        st.subheader("Classification Report")
        report = classification_report(y, y_pred, target_names=['<=50K', '>50K'])
        st.code(report)

# ══════════════════════════════════════════════════════════════════════════════
with tab2:
    st.subheader("All Models Comparison")
    if st.button("Run all 5 models"):
        rows = []
        progress = st.progress(0)
        for i, (mname, mpath) in enumerate(MODEL_FILES.items()):
            m   = load_model(mpath)
            yp  = m.predict(X)
            ypr = m.predict_proba(X)[:, 1]
            rows.append({
                "Model":     mname,
                "Accuracy":  round(accuracy_score(y, yp),    4),
                "AUC":       round(roc_auc_score(y, ypr),    4),
                "Precision": round(precision_score(y, yp),   4),
                "Recall":    round(recall_score(y, yp),      4),
                "F1":        round(f1_score(y, yp),          4),
                "MCC":       round(matthews_corrcoef(y, yp),  4),
            })
            progress.progress((i + 1) / len(MODEL_FILES))
        st.session_state["comp_df"] = pd.DataFrame(rows).set_index("Model")

    if "comp_df" in st.session_state:
        comp_df = st.session_state["comp_df"]
        st.dataframe(comp_df.style.highlight_max(axis=0, color="#c6efce").format(precision=4),
                     use_container_width=True)

        metric_choice = st.selectbox("Chart metric", comp_df.columns.tolist(), index=4)
        fig2, ax2 = plt.subplots(figsize=(8, 4))
        comp_df[metric_choice].sort_values().plot(kind='barh', ax=ax2,
                                                   color='#4C72B0', edgecolor='black')
        ax2.set_xlabel("Score")
        ax2.set_title(f"{metric_choice} — All Models")
        ax2.set_xlim(0, 1)
        st.pyplot(fig2)
    else:
        st.info("Click the button above to evaluate all 5 models on the uploaded data.")

# ══════════════════════════════════════════════════════════════════════════════
with tab3:
    st.subheader("Data Overview")
    st.write(f"Shape: {df.shape[0]} rows × {df.shape[1]} columns")

    st.markdown("**Class Balance**")
    vc = y.value_counts()
    fig3, ax3 = plt.subplots(figsize=(4, 2.5))
    vc.plot(kind='bar', ax=ax3, color=['#4C72B0', '#DD8452'], edgecolor='black')
    ax3.set_xticklabels(['<=50K (0)', '>50K (1)'], rotation=0)
    ax3.set_ylabel("Count")
    st.pyplot(fig3)

    st.markdown("**Data Preview (first 10 rows)**")
    st.dataframe(df.head(10), use_container_width=True)

    st.markdown("**Feature Summary**")
    st.dataframe(X.describe().round(2), use_container_width=True)
